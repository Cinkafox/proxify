#!/bin/sh
set -e

# Машина B: поднимает игровой UDP-сервер и прокси-клиента в одном контейнере
# (одно сетевое пространство — ответы сервера уходят в loopback, где их
# перехватывает сниффер прокси-клиента; см. LoopbackAliasManager).

# Игровой сервер в фоне.
python3 /app/gamesrv.py &
sleep 1

# Аргументы прокси-клиента передаются аргументами контейнера (см. docker-compose).
exec dotnet /app/Proxify.Client.dll "$@"
